public class Practice01 {
    public static void main(String[] args){

        // Typecasting in Java is the process of converting a variable from one data type to another data type. 
        // There are two types of typecasting: implicit and explicit.

        /*
         * Implicit Typecasting: Automatic conversion of smaller data type to larger data type.
         * Explicit Typecasting: Manual conversion of larger data type to smaller data type.
         */


        // Implicit Typecasting Example.

        int num1 = 10;
        double num2 = num1; // Implicit typecasting from int to double.

        System.out.println("num1:" +num1);
        System.out.println("num2:" +num2);
    }
}