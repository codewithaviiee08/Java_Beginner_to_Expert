public class Wedening {
    public static void main(String [] args){

        // Typecasting of Widening data types.
        /*
         * Widening Typecasting: Automatic conversion of smaller data type to larger data type.
         * This is done by the compiler without any loss of data.
         */

        int num3 = 20;
        long num4 = num3; // Implicit widening conversion.

        System.out.println("The value of num4 is: " + num4);

    }
    
}
