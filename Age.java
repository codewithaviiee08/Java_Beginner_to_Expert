public class Age {
    public static void main(String[] args) {

        // Declaring variables of different data types
        int age = 26;
        // double = data type that can store decimal numbers
        double height = 5.9;
        // char = data type that can store a single character
        char grade = 'A';
        // boolean = data type that can store true or false values
        boolean isStudent = true;
        // String = data type that can store a sequence of characters
        String name = "Abhijeet Tiwari";

        System.out.println("Name: " + name);
        System.out.println("Age: " + age);
        System.out.println("Height: " + height);
        System.out.println("Grade: " + grade);
        System.out.println("Is Student: " + isStudent);

        
    }
}
